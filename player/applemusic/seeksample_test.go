// sampleAt 返回时间线 tl 在 ms 时刻的读数。早于第一行的时刻按每 1024ms 一格往回推（此前一直在正常播放）。
func sampleAt(tl []reading, ms int) float64 {
	if d := tl[0].ms - ms; d > 0 {
		return tl[0].pos - float64((d+1023)/1024)
	}
	i := sort.Search(len(tl), func(i int) bool { return tl[i].ms > ms })
	return tl[i-1].pos
}

// replay 按 gapMs 的间隔轮询会话，读数由 pos 给出：ms 从 fromMs 起、到 toMs 为止（不含），对应的时刻是
// origin 加上 ms。返回下一次该读的 ms，接着回放下一段时传回来。不与 run 的自动推进（setTwin 的 playing）
// 混用。
func (h *harness) replay(origin time.Time, dur float64, fromMs, toMs, gapMs int, pos func(ms int) float64) int {
	ms := fromMs
	for ; ms < toMs; ms += gapMs {
		h.now = origin.Add(time.Duration(ms) * time.Millisecond)
		h.f.twins[realTwin] = mem.Twin{Dur: dur, Pos: pos(ms)}
		h.s.tick()
		h.drain()
	}
	return ms
}
